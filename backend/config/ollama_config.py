def get_model_timeout(model_name: str) -> int:
    """
    🕐 Возвращает подходящий таймаут для модели
    
    Для чайников: большие модели думают дольше, им нужно больше времени!
    """
    model_lower = model_name.lower()
    
    if any(large_model in model_lower for large_model in LARGE_MODELS):
        return TIMEOUTS["large"]
    elif any(rec_model in model_lower for rec_model in RECOMMENDED_MODELS):
        return TIMEOUTS["medium"]
    else:
        return TIMEOUTS["small"]

def get_generation_params(task: str = "chat") -> Dict:
    """
    🎛️ Возвращает параметры генерации для определенной задачи
    
    Для чайников: разные задачи требуют разных настроек!
    - Чат: баланс креативности и точности
    - Анализ: меньше креативности, больше фактов
    - Творчество: максимум креативности
    """
    return TASK_PARAMS.get(task, DEFAULT_GENERATION_PARAMS)

def is_large_model(model_name: str) -> bool:
    """
    🐘 Проверяет, является ли модель "большой"
    
    Большие модели требуют больше памяти, времени и терпения!
    """
    return any(large_model in model_name.lower() for large_model in LARGE_MODELS)

